"""Build the static genre-selection reconstruction demo page from pairs.json."""
import html
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
data = json.load(open(HERE / "pairs.json", encoding="utf-8"))
rows = data["rows"]

rows_html = "\n".join(
    f"""<tr>
<td>row {r['row']}</td>
<td><img class="spec" src="spectro/row{r['row']}_ref.png"
     alt="heard stimulus spectrogram, row {r['row']}"><div class="mut tiny">spectrogram only</div></td>
<td><img class="spec" src="spectro/row{r['row']}_gen.png"
     alt="reconstructed spectrogram, row {r['row']}">
     <audio controls preload="none" src="audio/{html.escape(r['gen_file'])}"></audio></td>
<td class="clap"><b>{r['cos_own']:.3f}</b> own<br><span class="mut">others {r['cos_others']:.3f}</span></td>
</tr>"""
    for r in rows
)

page = """<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Genre-selection reconstruction demo — Auditory EEG Bench</title>
<style>
:root{--ink:#1c2333;--mut:#5a6478;--line:#e4e8ee;--accent:#1565c0}
body{font:16px/1.6 Georgia,serif;max-width:1120px;margin:40px auto;padding:0 20px;color:var(--ink)}
h1{font-size:32px;line-height:1.15;margin:0 0 8px}
.lead{font-size:17px;color:var(--mut);margin:8px 0 18px}
.note{color:var(--mut);font-size:14px;margin:10px 0}
.tiny{font-size:12px;margin-top:4px}
a{color:var(--accent)}
.wrap{overflow-x:auto}
table{border-collapse:collapse;width:100%;table-layout:fixed}
th,td{padding:10px 12px;border-bottom:1px solid var(--line);vertical-align:top}
th{background:#f3f5f7;text-align:left;font-size:14px}
th:nth-child(1),td:nth-child(1){width:8%}
th:nth-child(2),td:nth-child(2){width:32%}
th:nth-child(3),td:nth-child(3){width:32%}
th:nth-child(4),td:nth-child(4){width:28%}
img.spec{width:100%;max-width:360px;height:auto;display:block;border:1px solid var(--line);
border-radius:6px;background:#fff}
audio{width:100%;max-width:360px;margin-top:8px}
.clap b{font-size:18px}
.mut{color:var(--mut)}
@media(max-width:820px){body{margin:24px auto}th,td{padding:8px 6px}}
</style></head>
<body>
<p><a href="../index.html">← Auditory EEG Bench</a> · <a href="../README.md">README</a></p>
<h1>Genre-selection reconstruction demo</h1>
<p class="lead">Each row is one held-out EEG window. The window's EEG selects a prompt from the
12-prompt library; the frozen MusicGen-small generates an 8-second clip from that prompt. The table
compares the heard stimulus with the reconstructed clip.</p>

<p class="note"><b>Copyright.</b> The heard recordings are commercial; only spectrograms are shown,
and no stimulus waveform is redistributed. Every playable clip on this page is generated by the
frozen model.</p>
<p class="note"><b>Aligned spectrograms.</b> The original and reconstructed tiles use the same time
axis (0–8 s), frequency axis (0–8 kHz), and colour scale, so each pair is directly comparable.</p>

<div class="wrap">
<table>
<thead><tr><th>window</th><th>original heard<br><span class="mut tiny">spectrogram only</span></th>
<th>reconstructed<br><span class="mut tiny">spectrogram + audio</span></th>
<th>CLAP cosine<br><span class="mut tiny">own / others</span></th></tr></thead>
<tbody>__ROWS__</tbody>
</table>
</div>

<p class="note"><b>What the CLAP columns mean.</b> “own” is the cosine between the generated clip and
the stimulus heard in that window; “others” is its mean cosine to the other 13 stimuli. This is a
demo-level similarity check, not a benchmark result.</p>
<p class="note"><b>Caveat.</b> This is an illustrative demo, not a benchmark result: no MOS was
collected, and the generated clips are not evidence of cross-subject genre decoding. The
same-prompt control is near zero, so the CLAP margin is genre-level rather than song-level.
See the <a href="../leaderboard/">benchmark leaderboard</a> for the evaluated claims.</p>
<p class="note">Source: <code>results/library_b/listen</code>. Generator: frozen MusicGen-small,
400 tokens, temperature 0.9, fixed seed. No raw EEG, stimulus waveform, or checkpoints are
redistributed.</p>
</body></html>"""

page = page.replace("__ROWS__", rows_html)
(HERE / "index.html").write_text(page, encoding="utf-8")
print("wrote", HERE / "index.html", "rows", len(rows))
